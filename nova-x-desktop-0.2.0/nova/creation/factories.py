def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


def _svg_bar_chart(title: str, labels: list[str], values: list[float], *, unit: str = "") -> str:
    w, h = 640, 360
    max_v = max([abs(v) for v in values] + [1.0])
    bars: list[str] = []
    n = max(1, len(values))
    slot = (w - 120) // n
    bar_w = max(18, min(64, slot - 16))
    palette = ("#38d6c5", "#4f8cff", "#f59e0b", "#a855f7", "#22c55e", "#ef4444")
    for idx, (lbl, val) in enumerate(zip(labels, values, strict=False)):
        bh = max(4, int((abs(val) / max_v) * 210))
        bx = 70 + idx * slot + (slot - bar_w) // 2
        by = 290 - bh
        col = palette[idx % len(palette)]
        bars.append(f'  <rect x="{bx}" y="{by}" width="{bar_w}" height="{bh}" fill="{col}" />')
        bars.append(f'  <text x="{bx}" y="314" fill="#cbd5e1" font-size="12">{lbl[:10]}</text>')
        bars.append(f'  <text x="{bx}" y="{max(28, by - 8)}" fill="#f8fafc" font-size="12">{val:.2f}{unit}</text>')
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">',
            f"  <title>{title}</title>",
            f'  <rect x="0" y="0" width="{w}" height="{h}" fill="#0b1424" />',
            f'  <text x="32" y="36" fill="#f1f5f9" font-size="18">{title[:46]}</text>',
            '  <line x1="56" y1="290" x2="604" y2="290" stroke="#475569" stroke-width="2" />',
            '  <line x1="56" y1="64" x2="56" y2="290" stroke="#475569" stroke-width="2" />',
            *bars,
            "</svg>",
            "",
        ]
    )


