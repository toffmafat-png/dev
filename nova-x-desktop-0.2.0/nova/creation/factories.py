@dataclass
class GameSession:
    width: int = 8
    height: int = 8
    player_x: int = 0
    player_y: int = 0
    hp: int = 3
    score: int = 0
    target_score: int = 3
    cores: set[tuple[int, int]] = field(default_factory=lambda: {(2, 0), (2, 2), (4, 2)})
    hazards: set[tuple[int, int]] = field(default_factory=lambda: {(1, 1), (3, 3)})
    turns: int = 0

    @property
    def status(self) -> str:
        if self.hp <= 0:
            return "defeat"
        if self.score >= self.target_score:
            return "victory"
        return "playing"

    def handle_input(self, action: str) -> dict[str, int | str]:
        delta = MOVES.get(action.upper().strip())
        if delta is None or self.status != "playing":
            return {"status": self.status, "x": self.player_x, "y": self.player_y, "score": self.score, "hp": self.hp}
        nx = max(0, min(self.width - 1, self.player_x + delta[0]))
        ny = max(0, min(self.height - 1, self.player_y + delta[1]))
        self.player_x, self.player_y = nx, ny
        self.turns += 1
        pos = (nx, ny)
        if pos in self.cores:
            self.cores.remove(pos)
            self.score += 1
        if pos in self.hazards:
            self.hp -= 1
        return {"status": self.status, "x": self.player_x, "y": self.player_y, "score": self.score, "hp": self.hp}

    def save(self, path: Path) -> Path:
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "width": self.width,
            "height": self.height,
            "player": [self.player_x, self.player_y],
            "hp": self.hp,
            "score": self.score,
            "target_score": self.target_score,
            "cores": [list(c) for c in sorted(self.cores)],
            "hazards": [list(h) for h in sorted(self.hazards)],
            "turns": self.turns,
        }
        out.write_text(json.dumps(payload, indent=2) + "\\n", encoding="utf-8")
        return out

